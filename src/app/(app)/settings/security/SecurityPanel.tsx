'use client';
import { useState } from 'react';

export function SecurityPanel({ initiallyEnabledAt }: { initiallyEnabledAt: string | null }) {
  const [enabledAt, setEnabledAt] = useState<string | null>(initiallyEnabledAt);
  const [secret, setSecret] = useState<string | null>(null);
  const [uri, setUri] = useState<string | null>(null);
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState<null | 'start' | 'verify' | 'disable'>(null);
  const [err, setErr] = useState<string | null>(null);
  const [msg, setMsg] = useState<string | null>(null);

  async function startEnroll() {
    setErr(null); setMsg(null); setBusy('start');
    try {
      const res = await fetch('/api/me/2fa/start', { method: 'POST' });
      const data = await res.json();
      if (!res.ok) throw new Error(data?.error?.message ?? `HTTP ${res.status}`);
      setSecret(data.data.secret);
      setUri(data.data.uri);
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally { setBusy(null); }
  }

  async function verifyCode(action: 'verify' | 'disable') {
    setErr(null); setMsg(null); setBusy(action);
    try {
      const res = await fetch(`/api/me/2fa/${action}`, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ code }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data?.error?.message ?? `HTTP ${res.status}`);
      setCode('');
      if (action === 'verify') {
        setEnabledAt(new Date().toISOString());
        setSecret(null); setUri(null);
        setMsg('Two-factor authentication enabled. You\'ll be asked for a code at next sign-in.');
      } else {
        setEnabledAt(null);
        setMsg('Two-factor authentication disabled.');
      }
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally { setBusy(null); }
  }

  return (
    <>
      {err && <div className="err">{err}</div>}
      {msg && <div className="err" style={{ background: 'rgba(46,160,67,0.15)', color: '#4ade80', borderColor: 'rgba(46,160,67,0.4)' }}>{msg}</div>}

      <section className="card">
        <h3>Two-factor authentication (TOTP)</h3>
        {enabledAt ? (
          <>
            <p>Status: <strong style={{ color: 'var(--ok)' }}>Enabled</strong> on <span className="mono">{new Date(enabledAt).toLocaleString()}</span>.</p>
            <p className="muted">Codes are generated by your authenticator app (Google Authenticator, Authy, 1Password, etc.) and refresh every 30 seconds.</p>
            <h4>Disable</h4>
            <p className="muted">Enter a current 6-digit code from your authenticator to turn 2FA off.</p>
            <div className="row" style={{ gap: 8 }}>
              <input className="input mono" style={{ width: 140 }} inputMode="numeric" pattern="\d{6}" maxLength={6} value={code} onChange={(e) => setCode(e.target.value)} placeholder="123456" />
              <button className="btn btn-danger" disabled={busy !== null || code.length !== 6} onClick={() => verifyCode('disable')}>{busy === 'disable' ? 'Disabling…' : 'Disable 2FA'}</button>
            </div>
          </>
        ) : secret && uri ? (
          <>
            <p>Scan this with your authenticator — or type the secret manually.</p>
            <div className="card" style={{ background: 'var(--bg-input)', margin: 0 }}>
              <div className="dim" style={{ fontSize: 11, textTransform: 'uppercase', letterSpacing: '0.05em', marginBottom: 4 }}>Shared secret</div>
              <div className="mono" style={{ fontSize: 18, letterSpacing: '0.08em', wordBreak: 'break-all' }}>{secret}</div>
              <div className="dim" style={{ fontSize: 11, textTransform: 'uppercase', letterSpacing: '0.05em', marginBottom: 4, marginTop: 10 }}>Setup URI</div>
              <code style={{ fontSize: 11, wordBreak: 'break-all', color: 'var(--text-muted)' }}>{uri}</code>
            </div>
            <h4 style={{ marginTop: 14 }}>Confirm</h4>
            <p className="muted">Enter the current 6-digit code shown in your authenticator app:</p>
            <div className="row" style={{ gap: 8 }}>
              <input className="input mono" style={{ width: 140 }} inputMode="numeric" pattern="\d{6}" maxLength={6} value={code} onChange={(e) => setCode(e.target.value)} placeholder="123456" autoFocus />
              <button className="btn btn-primary" disabled={busy !== null || code.length !== 6} onClick={() => verifyCode('verify')}>{busy === 'verify' ? 'Verifying…' : 'Enable 2FA'}</button>
            </div>
          </>
        ) : (
          <>
            <p>Status: <strong>Not enabled</strong>.</p>
            <p className="muted">Enrolling binds a shared secret to your account; signing in will then require your password <em>and</em> a current 6-digit code from your authenticator app.</p>
            <button className="btn btn-primary" disabled={busy !== null} onClick={startEnroll}>{busy === 'start' ? 'Generating…' : 'Begin enrollment'}</button>
          </>
        )}
      </section>
    </>
  );
}
